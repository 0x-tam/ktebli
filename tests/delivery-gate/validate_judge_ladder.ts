console.log(`ground truth: ${docs.length} documents, ${data.length} critic judgements, ${disputed.length} DISPUTED (excluded from the rate):`);
for (const d of docs) {
  console.log(`  ${(d.rung + "-" + d.arm).padEnd(12)} gen=${d.generator.padEnd(28)} [${d.judgements.map((j) => `${j.critic.slice(-1)}:${j.verdict === "fundable" ? "Y" : "N"}`).join(" ")}] -> ${d.consensus}`);
}
const decided = docs.filter((d) => d.consensus !== "disputed");
const fundableDocs = decided.filter((d) => d.consensus === "fundable").length;
console.log(`corpus balance (documents): ${fundableDocs} fundable, ${decided.length - fundableDocs} not fundable, ${disputed.length} disputed`);
console.log(`candidates: ${MODELS.join(", ")} · fixed: temp ${JUDGE_TEMPERATURE}, seed ${JUDGE_SEED}, effort ${JUDGE_EFFORT}, structured outputs, NEUTRAL v2 instrument`);
console.log(`budget: $${BUDGET_USD.toFixed(2)} HARD\n`);

if (DRY) {
  const req = buildJudgeRequest(judgeView(gateInputFor(docs[0])), { ...JUDGE_SLOTS[0], model: MODELS[0] });
  console.log(`--dry-run: up to ${docs.length * MODELS.length} calls. First request: model=${req.model} effort=${req.effort} temp=${req.temperature} seed=${req.seed} prompt=${req.prompt.length} chars schema=${req.responseFormat?.json_schema.name}`);
  Deno.exit(0);
}
if (!KEY) {
  console.error("OPENROUTER_API_KEY is not set. Refusing to report an agreement rate that was never measured.");
  Deno.exit(1);
}

const rows: Row[] = [];
let stopped: string | null = null;
outer:
for (const model of MODELS) {
  for (const d of docs) {
    if (modelFamily(model) === modelFamily(d.generator)) {
      console.error(`  ${model} ${d.rung}-${d.arm}: SKIPPED (generator's own family; never judged, never billed)`);
      continue;
    }
    try {
      const r = await judgeOne(d, model);
      rows.push(r);
      console.error(`  ${model} ${d.rung}-${d.arm}: ${r.gate}${r.score !== null ? ` (score ${r.score})` : ""}${r.error ? ` [${r.error.slice(0, 80)}]` : ""} $${(r.usd ?? 0).toFixed(4)}`);
    } catch (e) {
      if (e instanceof BudgetStop) { stopped = String(e.message); break outer; }
      throw e;
    }
  }
}

console.log(`\nmodel                              n(data)  agree  rate    always-hold  false-pass  false-hold  missing  own-family-excluded`);
for (const model of MODELS) {
  if (!rows.some((r) => r.model === model)) continue;
  const s = rateFor(rows, model);
  console.log(
    `${model.padEnd(34)} ${String(s.n).padEnd(8)} ${String(s.agree).padEnd(6)} ${(s.rate * 100).toFixed(1).padStart(5)}%  ` +
    `${(s.baseline * 100).toFixed(1).padStart(10)}%  ${String(s.falsePass).padStart(10)}  ${String(s.falseHold).padStart(10)}  ` +
    `${String(s.missing).padStart(7)}  ${String(s.excluded).padStart(3)} doc(s)`,
  );
  if (s.n && s.rate <= s.baseline) console.log(`   ^ NO SIGNAL: does not beat refusing everything.`);
}
console.log(`\nDISPUTED documents excluded from every rate: ${disputed.length} (${disputed.map((d) => `${d.rung}-${d.arm}`).join(", ")})`);
console.log(`total measured spend: $${spentUsd.toFixed(4)} over ${rows.length} judged documents` +
  (unmeasuredCalls ? `; ${unmeasuredCalls} call(s) carried no cost accounting` : ""));
if (stopped) console.log(`STOPPED BEFORE THE BUDGET: ${stopped}. Documents not judged are reported MISSING/absent, never guessed.`);

console.log(`\nDecision rule (phase brief): wire the primary if agreement >= 80%; else try the fallback as primary;` +
  ` if both miss, wire the better one hold-biased and flag LOW-AGREEMENT.`);
